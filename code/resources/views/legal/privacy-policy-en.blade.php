                <strong>Management of bookings and services offered</strong>: including table reservations, waiting list,
                loyalty card, any free Wi-Fi, transactional messages and management of the User’s requests.
                <strong>Legal basis</strong>: performance of pre-contractual/contractual measures (Article 6(1)(b) GDPR).
            </li>
            <li>
                <strong>Legal, accounting and tax compliance</strong>: fulfilment of obligations provided for by law and by provisions of the authorities.
                <strong>Legal basis</strong>: legal obligation (Article 6(1)(c) GDPR).
            </li>
            <li>
                <strong>Administrative and security purposes</strong>: prevention and detection of unlawful/fraudulent activities, legal defence.
                <strong>Legal basis</strong>: legitimate interest (Article 6(1)(f) GDPR).
            </li>
            <li>
                <strong>Statistics</strong>: internal statistical analyses in anonymous/aggregated form to improve service quality.
                <strong>Legal basis</strong>: legitimate interest.
            </li>
            <li>
                <strong>Restaurant marketing</strong>: sending promotional communications/newsletters/surveys via automated or traditional channels.
                <strong>Legal basis</strong>: consent (Article 6(1)(a) GDPR).
            </li>
            <li>
                <strong>Restaurant profiling</strong>: analysis of preferences/habits for targeted communications.
                <strong>Legal basis</strong>: consent.
            </li>
        </ol>

        <p class="mb-2 opacity-[0.7]"><strong>4.B – Processing carried out by Webofficine Srls (independent Controller)</strong></p>
        <p class="mb-4 opacity-[0.7]">
            Webofficine Srls processes data as an independent Data Controller only for the following purposes, where the relevant conditions are met.
        </p>
        <ol class="list-decimal list-inside space-y-2 mb-4 opacity-[0.7] ml-4">
            <li>
                <strong>“Risto Pilot” network marketing</strong>: sending promotional communications relating to restaurants participating in the network other
                than the one where the User provided their data (e.g., offers, discounts, initiatives). <strong>Legal basis</strong>: consent
                (Article 6(1)(a) GDPR); for electronic channels, Article 130 of the Italian Privacy Code applies.
            </li>
            <li>
                <strong>“Light” profiling for personalisation</strong>: segmentation into clusters (e.g., geographic area, visit frequency, type
                of cuisine inferred from bookings) in order to send more relevant communications. <strong>Legal basis</strong>: consent.
            </li>
            <li>
                <strong>Network-wide analytics</strong>: aggregated or anonymised statistical processing to measure network performance and create
                benchmarks for participating Customers. <strong>Legal basis</strong>: legitimate interest (Article 6(1)(f) GDPR) with minimisation
                and anonymisation; where anonymisation is not technically possible, Webofficine relies on the User’s consent.
            </li>
        </ol>

