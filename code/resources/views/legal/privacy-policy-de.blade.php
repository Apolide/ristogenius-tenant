        <!-- Sezione 8 -->
        <h2 class="text-lg font-semibold mb-2">8. Folgen der Nichtbereitstellung von Daten</h2>
        <p class="mb-4 opacity-[0.7]">
            Die Bereitstellung von Daten für Zwecke im Zusammenhang mit den Dienstleistungen (z. B. Buchungen, vertragliche und gesetzliche Verpflichtungen) ist erforderlich, um die Dienstleistungen des Verantwortlichen nutzen zu können.
            Werden diese Daten nicht bereitgestellt, ist es möglicherweise nicht möglich, die angeforderten Dienstleistungen zu erbringen.
        </p>
        <p class="mb-4 opacity-[0.7]">
            Die Bereitstellung von Daten für Marketing- und Profilingzwecke ist freiwillig; eine Nichterteilung der Einwilligung beeinträchtigt die Nutzung der Hauptdienstleistungen nicht.
        </p>

