                                </p>
                                <ul class="list-disc list-inside space-y-2 mb-4 opacity-[0.7] ml-4">
                                    <li>
                                        <strong>Servizi core</strong>: il ristorante utilizza RISTOPILOT per l’erogazione dei servizi core; in tale ambito Webofficine opera come
                                        Responsabile del trattamento ex art. 28 GDPR.
