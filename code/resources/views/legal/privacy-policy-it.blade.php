                                        Eventuali dati particolari (es. allergie) non sono trasferiti per tali finalità.
                                    </li>
                                    <li>
                                        <strong>Ambito interno</strong>: i dati possono essere trattati da personale del Titolare incaricato e formato.
                                    </li>
                                    <li>
                                        <strong>Ambito esterno</strong>: i dati possono essere comunicati a fornitori necessari (es. servizi IT, consulenti contabili/fiscali, gestori
                                        della piattaforma) nei limiti necessari e con adeguate garanzie, anche in Paesi extra UE mediante strumenti conformi al GDPR (es. Clausole Contrattuali Standard).
                                    </li>
                                    <li>
                                        <strong>Autorità</strong>: i dati possono essere comunicati a enti o autorità pubbliche ove previsto dalla legge.
                                    </li>
                                </ul>

